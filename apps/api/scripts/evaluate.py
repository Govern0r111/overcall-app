from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any
from uuid import UUID

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from overcall.detection.base import LogRow, RuleContext
from overcall.detection.registry import RULES
from overcall.detection.thresholds import Thresholds
from overcall.synthetic.generator import generate
from overcall.synthetic.truth import GroundTruth

ROOT = Path(__file__).resolve().parents[3]
SMALL_FIXTURE = ROOT / "contract" / "fixtures" / "synthetic" / "small"
REPORT_PATH = ROOT / "validation" / "reports" / "synthetic.json"
BASELINE_PATH = ROOT / "validation" / "baseline.json"


def evaluate_dataset(
    records: list[dict[str, Any]],
    truth: GroundTruth,
    rules=RULES,
) -> dict[str, Any]:
    logs = [LogRow.from_record(record) for record in records]
    logs.sort(key=lambda row: (row.occurred_at, row.id))
    window_days = (
        max(
            0.0,
            (logs[-1].occurred_at - logs[0].occurred_at).total_seconds() / 86_400,
        )
        if logs
        else 0.0
    )
    context = RuleContext(
        thresholds=Thresholds(),
        window_days=max(window_days, 1.0),
        now=datetime.now(UTC),
    )
    metrics = []
    for rule in rules:
        flagged = {
            request_id
            for finding in rule.detect(logs, context)
            for request_id in finding.waste_by_request
        }
        positives = {UUID(request_id) for request_id in truth.request_ids(rule.id)}
        hard_negatives = {
            UUID(request_id) for request_id in truth.request_ids(rule.id, "hard_negative")
        }
        true_positives = flagged & positives
        metrics.append(
            {
                "rule_id": rule.id,
                "tier": rule.tier,
                "positives": len(positives),
                "flagged": len(flagged),
                "true_positives": len(true_positives),
                "precision": (
                    round(len(true_positives) / len(flagged), 4)
                    if flagged
                    else (1.0 if not positives else 0.0)
                ),
                "recall": (
                    round(len(true_positives) / len(positives), 4)
                    if positives
                    else 1.0
                ),
                "hard_negatives": len(hard_negatives),
                "false_positives_on_hard_negatives": len(flagged & hard_negatives),
            }
        )
    return {
        "dataset": "synthetic",
        "generator_version": truth.generator_version,
        "note": (
            "Synthetic fixtures are generated by a known process; high scores are not evidence "
            "of real-traffic accuracy."
        ),
        "generated_at": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        "requests": len(logs),
        "rules": metrics,
    }


def assert_no_regression(report: dict[str, Any], baseline: dict[str, Any]) -> None:
    baseline_version = baseline.get("generator_version")
    report_version = report.get("generator_version")
    if baseline_version is not None and report_version != baseline_version:
        raise SystemExit(
            "Synthetic baseline generator version mismatch: "
            f"{report_version!r} != {baseline_version!r}"
        )
    baseline_rules = {
        item["rule_id"]: item
        for item in baseline.get("rules", [])
        if isinstance(item, dict) and "rule_id" in item
    }
    for result in report["rules"]:
        prior = baseline_rules.get(result["rule_id"])
        if not prior:
            continue
        for metric in ("precision", "recall"):
            if result[metric] < prior[metric]:
                raise SystemExit(
                    f"{result['rule_id']} {metric} regressed: "
                    f"{result[metric]} < baseline {prior[metric]}"
                )


def regenerate_records(truth: GroundTruth) -> list[dict[str, Any]]:
    """Rebuild full rows from the committed seed.

    The public fixture omits internal detection fields (context hash, tool use), so
    evaluation regenerates the dataset and checks it still matches the committed labels.
    """
    logs, regenerated = generate(seed=truth.seed)
    if regenerated.model_dump(mode="json") != truth.model_dump(mode="json"):
        raise SystemExit("Committed ground truth does not match the generator; regenerate it")
    return [log.to_record() for log in logs]


def main() -> None:
    truth = GroundTruth.model_validate_json(
        (SMALL_FIXTURE / "ground_truth.json").read_text(encoding="utf-8")
    )
    records = regenerate_records(truth)
    report = evaluate_dataset(records, truth)
    if BASELINE_PATH.exists():
        baseline = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
        assert_no_regression(report, baseline)
        report["baseline_checked"] = True
    else:
        report["baseline_checked"] = False
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
